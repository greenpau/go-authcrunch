def makeTypeStruct(t):
    output = []
    ct = t['cond_data_type']
    mt = t['match_type']
    negativeMatch = t['negative']
    if negativeMatch:
        matchKeyword = "not match"
    else:
        matchKeyword = "match"

    description = "%s %ses %s" % (
        t['name'], matchKeyword, INPUTDATA[t['input_data_type']]['description'])
    description += " %s" % (CONDS[t['cond_data_type']]['description'])

    if 'List' in t['cond_data_type']:
        description += " where any of the input values %s at least one value of the condition" % (matchKeyword)
    description += " using %s %s." % (
        MATCHES[t['match_type']]['description'], matchKeyword)
    for line in textwrap.wrap(description, width=80):
        output.append("// " + line)
    output.append("type %s struct {" % (t['name']))

    ts_attrs = []
    if mt in CONDS[ct]['attrs']:
        ts_attrs = CONDS[ct]['attrs'][mt]
    else:
        ts_attrs = CONDS[ct]['attrs']['default']
    for ts_attr in ts_attrs:
        output.append("    %s" % (ts_attr))
    output.extend(['}', ''])
    return output


