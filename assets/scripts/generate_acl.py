def render():
    """Render and format every artifact before touching any destination."""
    generators = {
        'condition.go': generateConditionCode,
        'condition_test.go': generateConditionTests,
        'rule.go': generateRuleCode,
        'rule_test.go': generateRuleTests,
    }
    output = {}
    for name, generate in generators.items():
        source = GO_HEADER + generate().lstrip()
        result = subprocess.run(['gofmt'], input=source.encode('utf-8'), capture_output=True, check=False)
        if result.returncode:
            raise ValueError('gofmt failed for %s: %s' % (name, result.stderr.decode('utf-8', errors='replace').strip()))
        output[name] = result.stdout
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='report missing or stale generated files without writing')
    args = parser.parse_args()
    try:
        output = render()
        destination = ROOT / 'pkg/acl'
        changed = [name for name, content in output.items()
                   if not (destination / name).exists() or (destination / name).read_bytes() != content]
        if args.check:
            for name in changed:
                print('out of date: pkg/acl/%s (run make generate-acl)' % name, file=sys.stderr)
            return 1 if changed else 0
        if changed:
            destination.mkdir(parents=True, exist_ok=True)
            # Stage all files first; replace each destination with a complete file.
            # A rendering, formatting, or staging failure leaves existing files intact.
            with tempfile.TemporaryDirectory(prefix='.generate-acl-', dir=destination) as directory:
                staged = Path(directory)
                for name in changed:
                    path = staged / name
                    path.write_bytes(output[name])
                    if (destination / name).exists():
                        path.chmod((destination / name).stat().st_mode & 0o777)
                for name in changed:
                    (staged / name).replace(destination / name)
                    print('generated pkg/acl/%s' % name)
        else:
            print('ACL generated files are up to date')
        return 0
    except (OSError, ValueError) as exc:
        print('generate-acl: %s' % exc, file=sys.stderr)
        return 2


if __name__ == '__main__':
    sys.exit(main())
