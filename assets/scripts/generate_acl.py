def makeTestEvalAclRule(t):
    output = []
    LOG.debug("entry: %s", t)

    for k in VERDICTS.keys():
        name = t['metadata']['name']
        name += ' with %s verdict' % (VERDICTS[k])
        if 'Stop' in k and 'Stop' not in t['metadata']['struct_name']:
            continue

        if k in ['Allow', 'Deny'] and 'Stop' in t['metadata']['struct_name']:
            continue

        if "Allow" in k or "Deny" in k:
            if 'DenyStop' in t['metadata']['struct_name'] and 'DenyStop' not in k:
                continue
            if 'AllowStop' in t['metadata']['struct_name'] and 'AllowStop' not in k:
                continue
            if 'Deny' in t['metadata']['struct_name'] and "Allow" in k:
                continue
            if 'Allow' in t['metadata']['struct_name'] and "Deny" in k:
                continue
            if 'All' in t['metadata']['struct_name']:
                req = [{
                    "roles": {
                        "value": ["foobar"],
                        "type": "ListStr",
                    },
                    "org": {
                        "value": ["nyc"],
                        "type": "ListStr",
                    },
                }]
            else:
                req = [{
                    "roles": {
                        "value": ["foobar"],
                        "type": "ListStr",
                    },
                }]
        elif "Continue" in k:
            req = [
                {
                    "name": {
                        "value": "John Smith",
                        "type": "Str",
                    },
                    "roles": {
                        "value": ["barfoo"],
                        "type": "ListStr",
                    },
                },
                {
                    "name": {
                        "value": "John Smith",
                        "type": "Str",
                    },
                },
                {
                    "empty_fields": True,
                    "name": {
                        "value": "John Smith",
                        "type": "Str",
                    },
                    "roles": {
                        "value": ["barfoo"],
                        "type": "ListStr",
                    },
                },
                {
                    "empty_fields": True,
                    "name": {
                        "value": "John Smith",
                        "type": "Str",
                    },
                },
            ]
        for i, entry in enumerate(req):
            tc = '{'
            if i > 0:
                tc += '    name: "%s %d",\n' % (name, i)
            else:
                tc += '    name: "%s",\n' % (name)
            tc += '    config: %s,' % ('\n'.join(t['config']))
            tc += '    input: map[string]interface{}{\n'
            for field in entry:
                if field == "empty_fields":
                    continue
                if entry[field]['type'] == 'ListStr':
                    tc += '      "%s": []string{"%s"},\n' % (field, '", "'.join(entry[field]['value']))
                elif entry[field]['type'] == 'Str':
                    tc += '      "%s": "%s",\n' % (field, entry[field]['value'])
            tc += '    },\n'
            for field in entry:
                if field != "empty_fields":
                    continue
                tc += 'emptyFields: true,\n'
            tc += '    want: map[string]interface{}{\n'
            tc += '        "verdict": getRuleVerdictName(ruleVerdict%s),\n' % (k)
            for field in entry:
                if field != "empty_fields":
                    continue
                tc += '"empty_fields": true,\n'
            tc += '        "rule_type": "*acl.%s",\n' % (t['metadata']['struct_name'])
            tc += '    },\n'
            tc += '},\n'
            output.append(tc.strip())
    return output


