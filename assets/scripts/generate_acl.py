def makeMatchFunction(t):
    ct = t['cond_data_type']
    it = t['input_data_type']
    mt = t['match_type']
    negativeMatch = t['negative']
    output = []

    if mt == 'Always':
        output.append('''
        func (c *%s) match(ctx context.Context, v interface{}) bool {
            return true
        }
        ''' % (t['name']))
        return output

    if ct not in CONDS or it not in INPUTDATA:
        raise Exception(
            "bad condition: condition value type %s, input value type: %s" % (ct, it))

    parameter = 'values' if it == 'ListStr' else 'v'
    output.append('func (c *%s) match(ctx context.Context, %s interface{}) bool {' % (t['name'], parameter))
    loops = []
    if ct == 'ListStr':
        loops.append('for _, exp := range c.exprs {')
    if it == 'ListStr':
        loops.append('for _, v := range values.([]string) {')

    # Preserve the existing negative-regex "match any" semantics: one
    # nonmatching pair suffices, whereas the default rejects any matching pair.
    if negativeMatch and mt == 'Regex' and loops:
        output.append('if c.config.matchAny {')
        output.extend(loops)
        output.append('if !%s.MatchString(%s) { return true }' % (CONDS[ct]['cmp'], INPUTDATA[it]['cmp']))
        output.extend('}' for _ in loops)
        output.append('return false\n}')

    output.extend(loops)
    output.extend(makeCompare(ct, it, mt, negativeMatch))
    output.extend('}' for _ in loops)
    output.append('return %s\n}' % ('true' if negativeMatch else 'false'))

    return output


