func newJWKSPortal(t *testing.T, directives ...string) *Portal {
	t.Helper()
	cfg, err := kms.NewCryptoKeyStoreConfig(directives)
	if err != nil {
		t.Fatal(err)
	}
	ks, err := kms.NewCryptoKeyStore(cfg, zap.NewNop())
	if err != nil {
		t.Fatal(err)
	}
	// Missing session/authorization/UI runtimes ensure discovery is independent
	// of login state and does not invoke authenticated handlers.
	return &Portal{config: &PortalConfig{UI: &ui.Parameters{}}, cookie: &cookie.Factory{}, keystore: ks, logger: zap.NewNop()}
}

func requestJWKS(t *testing.T, p *Portal, method, target string, headers map[string]string) *httptest.ResponseRecorder {
	t.Helper()
	r := httptest.NewRequest(method, "https://auth.example.test"+target, nil)
	for k, v := range headers {
		r.Header.Set(k, v)
	}
	w := httptest.NewRecorder()
	rr := requests.NewRequest()
	if err := p.ServeHTTP(context.Background(), w, r, rr); err != nil {
		t.Fatal(err)
	}
	if len(w.Header().Values("Set-Cookie")) != 0 || w.Header().Get("Location") != "" || rr.Response.Authenticated {
		t.Fatal("JWKS request changed session state or redirected")
	}
	if w.Header().Get("Cache-Control") != "no-store" || w.Header().Get("X-Content-Type-Options") != "nosniff" {
		t.Fatal("missing JWKS cache or content-type protection")
	}
	return w
}

func TestPortalJWKS(t *testing.T) {
	p := newJWKSPortal(t)
	cases := []struct {
		name, path string
		headers    map[string]string
	}{
		{"root", "/.well-known/jwks.json", nil},
		{"default mount", "/auth/.well-known/jwks.json", nil},
		{"custom mount", "/xauth/.well-known/jwks.json", nil},
		{"nested mount", "/tenant/xauth/.well-known/jwks.json", nil},
		{"API in mount", "/api/xauth/.well-known/jwks.json", nil},
		{"QR code in mount", "/qrcode/xauth/.well-known/jwks.json", nil},
		{"profile in mount", "/profile/xauth/.well-known/jwks.json", nil},
		{"JSON query", "/xauth/.well-known/jwks.json?format=json", nil},
		{"unrelated query", "/xauth/.well-known/jwks.json?redirect_url=https://other.example.test", nil},
		{"JSON content type", "/xauth/.well-known/jwks.json", map[string]string{"Content-Type": "application/json", "Accept": "application/json"}},
		{"JWK content negotiation", "/xauth/.well-known/jwks.json", map[string]string{"Accept": "application/jwk-set+json"}},
		{"invalid credentials ignored", "/xauth/.well-known/jwks.json", map[string]string{"Authorization": "Bearer invalid", "Cookie": "access_token=invalid; AUTHP_SESSION_ID=invalid"}},
		{"encoded endpoint", "/xauth/%2ewell-known/%6awks.json", nil},
	}
	var reference []byte
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			w := requestJWKS(t, p, "GET", tc.path, tc.headers)
			if w.Code != http.StatusOK {
				t.Fatalf("got status %d", w.Code)
			}
			if w.Header().Get("Content-Type") != "application/jwk-set+json" {
				t.Fatal("unexpected content type")
			}
			if w.Header().Get("Content-Length") != strconv.Itoa(w.Body.Len()) {
				t.Fatal("incorrect content length")
			}
			var set struct {
				Keys []map[string]string `json:"keys"`
			}
			if err := json.Unmarshal(w.Body.Bytes(), &set); err != nil {
				t.Fatal(err)
			}
			if len(set.Keys) != 1 || set.Keys[0]["kty"] != "EC" || set.Keys[0]["alg"] != "ES512" {
				t.Fatal("missing autogenerated public signing key")
			}
			if reference == nil {
				reference = append([]byte(nil), w.Body.Bytes()...)
			}
			if !bytes.Equal(reference, w.Body.Bytes()) {
				t.Fatal("mount, headers or query changed the public keys")
			}
		})
	}
	head := requestJWKS(t, p, "HEAD", "/xauth/.well-known/jwks.json", nil)
	if head.Code != http.StatusOK || head.Body.Len() != 0 || head.Header().Get("Content-Length") != strconv.Itoa(len(reference)) || head.Header().Get("Content-Type") != "application/jwk-set+json" {
		t.Fatal("HEAD does not describe GET without a body")
	}
	for _, method := range []string{"POST", "PUT", "DELETE", "PATCH", "OPTIONS", "TRACE"} {
		t.Run(method, func(t *testing.T) {
			w := requestJWKS(t, p, method, "/xauth/.well-known/jwks.json", nil)
			if w.Code != http.StatusMethodNotAllowed || w.Header().Get("Allow") != "GET, HEAD" || w.Body.Len() != 0 {
				t.Fatal("unsupported method was not rejected")
			}
		})
	}
}

func TestPortalJWKSUnavailable(t *testing.T) {
	const shared = "crypto key shared sign-verify synthetic-jwks-shared-secret"
	const rsa = "crypto key signing sign-verify from file ../../testdata/rskeys/test_2_pri.pem"
	for _, tc := range []struct {
		name       string
		directives []string
	}{
		{"HMAC", []string{shared}},
		{"HMAC before RSA", []string{shared, rsa}},
		{"public verifier", []string{"crypto key verify from file ../../testdata/rskeys/test_2_pub.pem"}},
		{"system only", []string{"crypto key internal system 0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			p := newJWKSPortal(t, tc.directives...)
			for _, method := range []string{"GET", "HEAD"} {
				w := requestJWKS(t, p, method, "/xauth/.well-known/jwks.json", nil)
				if w.Code != http.StatusNotFound || w.Body.Len() != 0 {
					t.Fatal("non-asymmetric issuer published JWKS")
				}
			}
		})
	}
	p := newJWKSPortal(t)
	p.keystore = nil
	if w := requestJWKS(t, p, "GET", jwksPath, nil); w.Code != http.StatusNotFound {
		t.Fatal("missing keystore should return 404")
	}
	p = newJWKSPortal(t)
	p.keystore.GetSignKeys()[0].Sign.Secret = []byte("synthetic-invalid-private-key")
	for _, method := range []string{"GET", "HEAD"} {
		w := requestJWKS(t, p, method, jwksPath, nil)
		if w.Code != http.StatusInternalServerError || w.Body.Len() != 0 {
			t.Fatal("invalid signer must fail without key material or errors in the response")
		}
	}
}

