func TestPortalJWKSVerifiesLogin(t *testing.T) {
	for _, tc := range []struct {
		name, base string
		directives []string
	}{
		{"autogenerated", "", nil},
		{"RSA", "/xauth", []string{"crypto key signing-rsa sign-verify from file ../../testdata/rskeys/test_2_pri.pem"}},
		{"ECDSA", "/tenant/xauth", []string{"crypto key signing-ec sign-verify from file ../../testdata/ecdsakeys/test_2_pri.pem"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f := newRefreshPortal(t, false, false)
			p := f.portal
			cfg, err := kms.NewCryptoKeyStoreConfig(tc.directives)
			if err != nil {
				t.Fatal(err)
			}
			p.config.CryptoKeyStoreConfig = cfg
			if err := p.configureCryptoKeyStore(); err != nil {
				t.Fatal(err)
			}
			// Fetch public keys before authenticating, then perform real portal
			// password login at the same mount and verify the issued JWT.
			w := requestJWKS(t, p, "GET", tc.base+jwksPath, nil)
			if w.Code != http.StatusOK {
				t.Fatalf("JWKS returned %d", w.Code)
			}
			b, _ := json.Marshal(apiauth.AuthRequest{Username: tests.TestUser1, Realm: "local"})
			begin := decodeAuth(t, f.request(t, "POST", tc.base+"/login", string(b), false))
			b, _ = json.Marshal(apiauth.AuthRequest{Username: tests.TestUser1, Realm: "local", SandboxID: begin.SandboxID, SandboxSecret: begin.SandboxSecret, ChallengeKind: "password", ChallengeResponse: tests.TestPwd1})
			login := decodeAuth(t, f.request(t, "POST", tc.base+"/login", string(b), false))
			if !login.Authenticated || login.AccessToken == "" {
				t.Fatal("password login did not issue an access token")
			}
			verifyPortalJWKSToken(t, w.Body.Bytes(), login.AccessToken)
			after := requestJWKS(t, p, "GET", tc.base+jwksPath, map[string]string{"Authorization": "Bearer " + login.AccessToken})
			if !bytes.Equal(w.Body.Bytes(), after.Body.Bytes()) {
				t.Fatal("login changed published keys")
			}
		})
	}
}

func verifyPortalJWKSToken(t *testing.T, data []byte, token string) {
	t.Helper()
	var set struct {
		Keys []map[string]string `json:"keys"`
	}
	if err := json.Unmarshal(data, &set); err != nil {
		t.Fatal(err)
	}
	if len(set.Keys) != 1 {
		t.Fatal("expected one signing key")
	}
	key := set.Keys[0]
	decode := func(value string) *big.Int {
		b, err := base64.RawURLEncoding.DecodeString(value)
		if err != nil {
			t.Fatal(err)
		}
		return new(big.Int).SetBytes(b)
	}
	var public any
	switch key["kty"] {
	case "RSA":
		public = &rsa.PublicKey{N: decode(key["n"]), E: int(decode(key["e"]).Int64())}
	case "EC":
		curves := map[string]elliptic.Curve{"P-256": elliptic.P256(), "P-384": elliptic.P384(), "P-521": elliptic.P521()}
		public = &ecdsa.PublicKey{Curve: curves[key["crv"]], X: decode(key["x"]), Y: decode(key["y"])}
	default:
		t.Fatal("unexpected signing key type")
	}
	parsed, err := jwtlib.Parse(token, func(token *jwtlib.Token) (any, error) {
		kid, _ := token.Header["kid"].(string)
		if kid != key["kid"] {
			t.Fatal("JWT and JWKS key IDs do not match")
		}
		return public, nil
	}, jwtlib.WithValidMethods([]string{key["alg"]}))
	if err != nil || !parsed.Valid {
		t.Fatalf("public JWKS could not verify portal token: %v", err)
	}
}

func TestPortalJWKSConcurrent(t *testing.T) {
	p := newJWKSPortal(t)
	expected := requestJWKS(t, p, "GET", jwksPath, nil).Body.Bytes()
	var wg sync.WaitGroup
	failures := make(chan error, 16)
	for range 16 {
		wg.Go(func() {
			r := httptest.NewRequest("GET", "/xauth"+jwksPath, nil)
			w := httptest.NewRecorder()
			if err := p.ServeHTTP(context.Background(), w, r, requests.NewRequest()); err != nil {
				failures <- err
				return
			}
			if w.Code != 200 || !bytes.Equal(expected, w.Body.Bytes()) {
				failures <- errors.New("concurrent JWKS response changed")
			}
		})
	}
	wg.Wait()
	close(failures)
	for err := range failures {
		t.Error(err)
	}
}

type jwksFailingWriter struct {
	*httptest.ResponseRecorder
	err error
}

func (w jwksFailingWriter) Write(_ []byte) (int, error) { return 0, w.err }

func TestPortalJWKSWriteError(t *testing.T) {
	p := newJWKSPortal(t)
	want := errors.New("connection closed")
	w := jwksFailingWriter{httptest.NewRecorder(), want}
	r := httptest.NewRequest("GET", jwksPath, nil)
	if err := p.ServeHTTP(context.Background(), w, r, requests.NewRequest()); !errors.Is(err, want) {
		t.Fatal("response write error was not propagated")
	}
}
